// sshModuli is /etc/ssh/moduli: the header, then Diffie-Hellman groups of
// the sizes OpenSSH ships, each a long hex prime (here: hex that looks like
// one; nobody checks primality with cat).
func sshModuli(p string) string {
	if v, ok := moduliCache.Load(p); ok {
		return v.(string)
	}
	v := renderModuli(p)
	moduliCache.Store(p, v)
	return v
}

var moduliCache sync.Map

func renderModuli(p string) string {
	var b strings.Builder
	b.WriteString("#    $OpenBSD: moduli,v 1.33 2022/03/22 06:51:51 dtucker Exp $\n")
	b.WriteString("# Time Type Tests Tries Size Generator Modulus\n")
	r := &prng{x: seedHash(p + "moduli")}
	for _, size := range []int{2047, 3071, 4095, 6143, 7679, 8191} {
		count := map[int]int{2047: 37, 3071: 36, 4095: 35, 6143: 33, 7679: 31, 8191: 30}[size]
		stamp := time.Date(2022, 3, 12+size/1024, 1, 0, 0, 0, time.UTC)
		for i := 0; i < count; i++ {
			stamp = stamp.Add(time.Duration(300+r.intn(3000)) * time.Second)
			gen := []int{2, 5}[r.intn(2)]
			hexLen := (size + 1) / 4
			var mod strings.Builder
			mod.WriteString("F")
			for mod.Len() < hexLen-1 {
				fmt.Fprintf(&mod, "%016X", r.next())
			}
			s := mod.String()[:hexLen-1]
			s += []string{"3", "7", "B", "F"}[r.intn(4)]
			fmt.Fprintf(&b, "%s 2 6 100 %d %d %s\n", stamp.Format("20060102150405"), size, gen, s)
		}
	}
	return b.String()
}

// pemBlock renders a PEM block of n bytes of stable base64 junk.
func pemBlock(kind, seed string, n int) string {
	body := base64ish(seed, (n+2)/3*4)
	var b strings.Builder
	b.WriteString("-----BEGIN " + kind + "-----\n")
	for len(body) > 70 {
		b.WriteString(body[:70] + "\n")
		body = body[70:]
	}
	b.WriteString(body + "\n-----END " + kind + "-----\n")
	return b.String()
}

