// installTime is when the box was installed: the start of its dpkg history.
func (m *Machine) installTime() time.Time {
	return m.mtime("/var/log/installer", ageInstall).Truncate(time.Second)
}

// logFile is one generated log: where it lives, who owns it, and how to
// render it up to a given time (returning the content and its mtime).
type logFile struct {
	path     string
	mode     uint32
	uid, gid int
	render   func(end time.Time) ([]byte, time.Time)
}

func (m *Machine) logFiles() []logFile {
	syslogUID := 0
	if u := m.Profile.User("syslog"); u != nil {
		syslogUID = u.UID
	}
	pgUID := 0
	if u := m.Profile.User("postgres"); u != nil {
		pgUID = u.UID
	}
	nginx := func(errors bool) func(time.Time) ([]byte, time.Time) {
		return func(end time.Time) ([]byte, time.Time) {
			a, e, am, em := m.nginxLogs(end)
			if errors {
				return e, em
			}
			return a, am
		}
	}
	const adm = 4
	return []logFile{
		{"/var/log/auth.log", 0o640, syslogUID, adm, m.authLog},
		{"/var/log/syslog", 0o640, syslogUID, adm, m.syslog},
		{"/var/log/kern.log", 0o640, syslogUID, adm, m.kernLog},
		{"/var/log/nginx/access.log", 0o640, 33, adm, nginx(false)},
		{"/var/log/nginx/error.log", 0o640, 33, adm, nginx(true)},
		{"/var/log/postgresql/postgresql-14-main.log", 0o640, pgUID, adm, m.postgresLog},
		{"/var/log/bakery/app.log", 0o644, 1000, 1000, m.appLog},
		{"/var/log/dpkg.log", 0o644, 0, 0, m.dpkgLog},
	}
}

// renderedLog is one log as of some minute; logCache keeps the latest few
// so that machines with the same profile and clock (every test, and every
// session within a minute) share the work.
type renderedLog struct {
	data  []byte
	mtime time.Time
}

var (
	logCacheMu sync.Mutex
	logCache   = map[string]renderedLog{}
)

func (m *Machine) renderLog(l logFile, end time.Time) renderedLog {
	p := m.Profile
	key := fmt.Sprint(l.path, p.Hostname, p.IPv4, p.Gateway, p.MAC, p.Interface, p.Kernel, len(p.Users), m.BootTime.UnixNano(), end.UnixNano(), end.Location())
	logCacheMu.Lock()
	r, ok := logCache[key]
	logCacheMu.Unlock()
	if ok {
		return r
	}
	data, mtime := l.render(end)
	r = renderedLog{data, mtime}
	logCacheMu.Lock()
	if len(logCache) > 64 {
		clear(logCache)
	}
	logCache[key] = r
	logCacheMu.Unlock()
	return r
}

// writeLogs (re)writes every generated log into fsys as of end.
func (m *Machine) writeLogs(fsys *vfs.FS, end time.Time) error {
	for _, l := range m.logFiles() {
		r := m.renderLog(l, end)
		data, mtime := r.data, r.mtime
		opts := vfs.WriteOptions{Mode: fs.FileMode(l.mode), UID: l.uid, GID: l.gid}
		if err := fsys.WriteFile(l.path, data, opts); err != nil {
			return fmt.Errorf("%s: %w", l.path, err)
		}
		// WriteFile keeps the owner of an existing file; set it anyway.
		if err := fsys.Chown(l.path, l.uid, l.gid); err != nil {
			return err
		}
		if err := fsys.Chtimes(l.path, mtime); err != nil {
			return err
		}
	}
	return nil
}
