func TestDdReadsHeadersAndCapsZeroFill(t *testing.T) {
	in, s := testSession(t)
	// Mirai-style arch detection reads the first 52 bytes of a system ELF.
	out, errb, st := run(t, in, s, "dd bs=52 count=1 if=/bin/echo")
	if st != 0 || len(out) != 52 || !strings.HasPrefix(out, "\x7fELF\x02\x01\x01") {
		t.Errorf("dd ELF header = %d %q", st, out)
	}
	if !strings.HasPrefix(errb, "1+0 records in\n1+0 records out\n52 bytes copied, ") {
		t.Errorf("dd stats = %q", errb)
	}
	// A 100 MiB zero fill becomes an opaque file: the size is reported,
	// the bytes are never held.
	_, errb, st = run(t, in, s, "dd if=/dev/zero of=/tmp/z bs=1M count=100")
	if st != 0 || !strings.Contains(errb, "104857600 bytes (105 MB, 100 MiB) copied") {
		t.Errorf("dd zero fill = %d %q", st, errb)
	}
	info, err := s.FS.Stat("/tmp/z")
	if err != nil || info.Size != 104857600 {
		t.Errorf("/tmp/z = %+v %v", info, err)
	}
}

func TestChattrAndFile(t *testing.T) {
	in, s := testSession(t)
	if _, errb, st := run(t, in, s, "chattr +i /etc/passwd"); st != 0 || errb != "" {
		t.Errorf("chattr +i = %d %q", st, errb)
	}
	if _, errb, st := run(t, in, s, "chattr -ia /nonexistent"); st != 1 || !strings.Contains(errb, "No such file or directory while trying to stat /nonexistent") {
		t.Errorf("chattr missing = %d %q", st, errb)
	}
	out, _, _ := run(t, in, s, "file /tmp /etc/passwd /bin /usr/bin/ls /dev/null")
	for _, want := range []string{
		"/tmp:        sticky, directory\n",
		"/etc/passwd: ASCII text\n",
		"/bin:        symbolic link to usr/bin\n",
		"/usr/bin/ls: ELF 64-bit LSB pie executable, x86-64",
		"/dev/null:   character special (1/3)\n",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("file output missing %q:\n%s", want, out)
		}
	}
}

