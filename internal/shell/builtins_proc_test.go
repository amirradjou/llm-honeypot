func TestPrintfReusesFormat(t *testing.T) {
	in, s := testSession(t)
	cases := []struct{ line, want string }{
		{`printf '%s\n' a b c`, "a\nb\nc\n"},
		{`printf '%5s|%-3d|%03d\n' ab 7 5`, "   ab|7  |005\n"},
		{`printf '\x41\x4b\n'`, "AK\n"},
		{`printf '%x %o %c\n' 255 8 hello`, "ff 10 h\n"},
		{`printf '%b' 'a\tb\n'`, "a\tb\n"},
	}
	for _, c := range cases {
		if out, _, _ := run(t, in, s, c.line); out != c.want {
			t.Errorf("%s = %q, want %q", c.line, out, c.want)
		}
	}
}
